// The Account / Opportunity schema catalog.
//
// This is the single source of truth for "what fields do we track, and how do
// they map to Salesforce" — rendered on the Integrations page so an SE/AE can
// diff it against the real SFDC org before we wire a live connection.
//
// Salesforce API names: standard fields use their real API names (Name,
// StageName, Amount, CloseDate, NextStep, ForecastCategory, ...). Custom fields
// use a best-guess `__c` name and MUST be verified against your org — they are
// flagged `custom: true` and rendered with a "verify" badge in the UI.

export type SchemaFieldType =
  | "string"
  | "text"
  | "number"
  | "currency"
  | "percent"
  | "date"
  | "datetime"
  | "boolean"
  | "picklist"
  | "multipicklist"
  | "reference"
  | "email"
  | "phone"
  | "url";

export type SchemaField = {
  /** Internal field name in this app's data model (Prisma). */
  key: string;
  label: string;
  type: SchemaFieldType;
  /** Salesforce object this maps to, e.g. "Opportunity". */
  sfdcObject: string;
  /** Salesforce API field name, e.g. "StageName" or "Technical_Close_Date__c". */
  sfdcApiName: string;
  /** True for custom (__c) fields whose API name must be verified in the org. */
  custom: boolean;
  required?: boolean;
  /** What the field is. */
  description: string;
  /** Why an SE/AE cares about this field. */
  seValue: string;
  /** A representative example value (string-rendered). */
  example: string;
  picklistValues?: string[];
};

export type SchemaObject = {
  key: string;
  label: string;
  sfdcObject: string;
  /** How this object relates to the others (root vs related list). */
  relationship: string;
  description: string;
  fields: SchemaField[];
};

